//! Every piece of text of the site, in English, French and Spanish (the languages of the
//! Memoire website). Shared by the server (pages) and the browser bundle (the dashboard).

use crate::routes::Lang;

/// The texts of `lang`.
pub fn t(lang: Lang) -> &'static Texts {
    match lang {
        Lang::En => &EN,
        Lang::Fr => &FR,
        Lang::Es => &ES,
    }
}

/// A title and a paragraph.
pub type Item = (&'static str, &'static str);

/// A feature: short title, one-liner for the home page, longer explanation for /features.
pub struct Feature {
    pub title: &'static str,
    pub desc: &'static str,
    pub detail: &'static str,
}

